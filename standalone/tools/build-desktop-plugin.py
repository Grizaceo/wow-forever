#!/usr/bin/env python3
"""Bundle the standalone guide into the Hermes desktop plugin (desktop/plugin.js).

Public build only: no market prices, no private overlays. Users import their own
Auctionator.lua. Only scripts whose data has a redistributable licence are
inlined (see LICENSE-DATA.md): the market catalog is regenerated from data/; the
old catalog derived from an unlicensed addon and the azeroth.wiki scrape are rejected.

No game reads, network, package installation, or Hermes core changes.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]          # standalone/
DEFAULT = ROOT.parent / 'desktop' / 'plugin.js'     # the package's desktop half

CORE_SCRIPTS = {'market.js', 'market-catalog.js', 'market-ui.js', 'drop-data.js', 'market-farm.js',
                'market-history.js', 'market-deals.js', 'market-chart.js',
                'guide-hunter.js', 'guide-warrior.js',
                'guide-shaman.js', 'guide-legacy.js'}
# Never inlined: private payloads and data without a redistributable licence.
# market-catalog.js is regenerated from data/ by tools/build-catalogo-mercado.py; the
# old ForeverDungeonJournal-derived one is rejected by its source marker.
FORBIDDEN_MARKERS = ('HunterDropDataPrivate=', 'HunterMarketLocalScan=', 'HunterDropForever=',
                     'ForeverDungeonJournal')


def safe_script(source):
    return re.sub(r'</script', r'<\\/script', source, flags=re.I)


def generate():
    html = (ROOT / 'index.html').read_text()
    allowed = set(CORE_SCRIPTS)

    def inline(match):
        name = match.group(1)
        if name not in allowed:
            raise ValueError('Unapproved document script: ' + name)
        return '<script>' + safe_script((ROOT / name).read_text()) + '</script>'
    html, count = re.subn(r'<script src="([^"]+)"></script>', inline, html)
    assert count == len(allowed), (count, len(allowed))
    csp = "default-src 'none'; script-src 'unsafe-inline' blob:; style-src 'unsafe-inline'; img-src data:; worker-src blob:; connect-src 'none'; base-uri 'none'; form-action 'none'"
    html = html.replace('<meta charset="UTF-8">', '<meta charset="UTF-8">\n<meta http-equiv="Content-Security-Policy" content="' + csp + '">\n<script>/*HUNTER_BOOT*/</script>', 1)
    assert html.count('/*HUNTER_BOOT*/') == 1
    guest = safe_script((ROOT / 'desktop/guest.js').read_text())
    constants = '\n'.join('const ' + key + '=' + json.dumps(value, ensure_ascii=True) + ';' for key, value in [
        ('HUNTER_HTML', html), ('HUNTER_GUEST', guest), ('HUNTER_STANDALONE', 'wow-forever:guia')])
    template = (ROOT / 'desktop/plugin.mjs').read_text()
    header = ('// GENERATED by standalone/tools/build-desktop-plugin.py from the public source in this repo.\n'
              '// No bundled market data; users import Auctionator.lua. Includes GPL-3.0 data (drop-data.js, CMaNGOS classic-db);\n'
              '// distributed under GPL-3.0-or-later. See LICENSE-DATA.md.\n')
    source = header + template.replace('/* HUNTER_BUNDLE */', constants).replace('/* HUNTER_STORE */', (ROOT / 'desktop/state.mjs').read_text())
    for marker in FORBIDDEN_MARKERS:
        if marker in source:
            raise ValueError('Build would ship non-public data: ' + marker)
    return source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=DEFAULT)
    args = parser.parse_args()
    out = args.output
    source = generate()
    out.parent.mkdir(parents=True, exist_ok=True)
    # The watcher must never see a half-written plugin. Existing package untouched
    # until the complete bundle exists in the same filesystem.
    temp = out.with_name('.plugin-build-new')
    fd = os.open(temp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, 'w') as f:
        f.write(source)
        f.flush()
        os.fsync(f.fileno())
    os.replace(temp, out)
    out.chmod(0o644)
    print(json.dumps({'plugin': str(out), 'bytes': out.stat().st_size,
                      'sha256': hashlib.sha256(out.read_bytes()).hexdigest()}))


if __name__ == '__main__':
    main()
