// Builds desktop/plugin.js into a temp dir (no browser) and checks what the
// public bundle may and may not contain, plus build reproducibility.
import {execFileSync} from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root=new URL('..',import.meta.url).pathname;
const tmp=fs.mkdtempSync(path.join(process.env.TMPDIR||os.tmpdir(),'wow-plugin-build-'));
const a=path.join(tmp,'a.js'),b=path.join(tmp,'b.js');
const builder=path.join(root,'tools/build-desktop-plugin.py');
execFileSync('python3',[builder,'--output',a],{stdio:'pipe'});
execFileSync('python3',[builder,'--output',b],{stdio:'pipe'});
const src=fs.readFileSync(a,'utf8');
const sha=f=>crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');
const CSP="default-src 'none'; script-src 'unsafe-inline' blob:; style-src 'unsafe-inline'; img-src data:; worker-src blob:; connect-src 'none'; base-uri 'none'; form-action 'none'";
const results=[];
const check=(name,pass,evidence)=>{results.push({name,pass:!!pass,evidence});};
check('ships the GPL drop dataset',src.includes('HunterDropData='),{bytes:src.length});
check('ships GPL notice',src.includes('GPL-3.0-or-later')&&src.includes('CMaNGOS'));
check('ships farm, history, chart and deals engines',['HunterFarm','mergeSnapshots','priceChart','dealInfo'].every(k=>src.includes(k)));
check('generated header names the builder',src.startsWith('// GENERATED by standalone/tools/build-desktop-plugin.py'));
check('no private overlay payload',!src.includes('HunterDropDataPrivate='));
check('no bundled scan payload',!src.includes('HunterMarketLocalScan='));
check('market catalog is the public one, not ForeverDungeonJournal',src.includes('CMaNGOS classic-db + cliente WoW Forever')&&!src.includes('ForeverDungeonJournal'));
check('no azeroth.wiki spawn scrape',!src.includes('HunterDropForever='));
check('no RareScanner table data',!/NpcInfoTables|NpcLootChanceTables|ContainerLootChanceTables|ContainerInfoTables/.test(src));
check('no raw desktop bridge',!src.includes('hermesDesktop'));
check('reads Auctionator only through ctx.files',src.includes('requestFolder')&&src.includes('files.readText'));
check('no local absolute paths',!/file:\/\/\/|\/home\/[a-z]/.test(src));
check('CSP present once',src.split(CSP).length===2);
check('build is reproducible',sha(a)===sha(b),{a:sha(a),b:sha(b)});
const committed=path.join(root,'..','desktop','plugin.js');
check('committed desktop/plugin.js matches a fresh build',fs.existsSync(committed)&&sha(committed)===sha(a),{fresh:sha(a)});
for(const r of results)console.log(`${r.pass?'PASS':'FAIL'} ${r.name}${r.pass?'':' '+JSON.stringify(r.evidence??'')}`);
console.log(JSON.stringify({passed:results.filter(r=>r.pass).length,failed:results.filter(r=>!r.pass).length,bytes:src.length,sha256:sha(a)}));
fs.rmSync(tmp,{recursive:true,force:true});
if(results.some(r=>!r.pass))process.exitCode=1;
