#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""build-catalogo-mercado.py — catálogo de ítems del mercado de la app standalone,
generado SOLO desde data/ (CMaNGOS classic-db + tablas del cliente WoW Forever).

Reemplaza al catálogo que antes salía del addon ForeverDungeonJournal (sin licencia).
Mantiene el contrato que lee standalone/market-ui.js (window.HunterMarketCatalog,
schemaVersion 1): para cada ítem del botín de jefes de dungeons y raids, su nombre,
jefe, dungeon y rango de niveles. Determinista, solo stdlib.
"""

import argparse
import hashlib
import json
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir))
DATA = os.path.join(ROOT, 'data')
OUT = os.path.join(ROOT, 'standalone', 'market-catalog.js')


def cargar(nombre):
    with open(os.path.join(DATA, nombre), encoding='utf-8') as f:
        return json.load(f)


def sha256(nombre):
    with open(os.path.join(DATA, nombre), 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


def nombre(n):
    return (n or {}).get('en') or (n or {}).get('es') or ''


def construir():
    items = cargar('items.json')['items']
    dungeons = cargar('dungeons.json')
    salida = {}
    for iid, fila in items.items():
        es, en = fila[0], fila[1]
        entrada = {'name': en or es, 'sources': []}
        if es and es != en:
            entrada['nameEs'] = es
        salida[str(iid)] = entrada
    for mapa, d in sorted(dungeons.get('clasicos', {}).items(), key=lambda kv: int(kv[0])):
        niveles = d.get('niveles') or {}
        for jefe in d.get('jefes', []):
            for item, prob in jefe.get('botin', []):
                e = salida.get(str(item))
                if e is None:
                    continue
                e['sources'].append({
                    'dungeon': nombre(d.get('n')), 'location': nombre(d.get('n')),
                    'levelMin': niveles.get('min'), 'levelMax': niveles.get('max'),
                    'boss': nombre(jefe.get('n')), 'bossLevel': None,
                    'chance': prob, 'raid': bool(d.get('raid')),
                    'reference': 'data/dungeons.json#%s/%s' % (mapa, jefe.get('npc')),
                })
    # Solo los ítems con fuente: la app standalone nombra el resto con drop-data.js. La
    # mitad Desktop nueva lee los nombres completos de data/items.json.
    salida = {k: e for k, e in salida.items() if e['sources']}
    for e in salida.values():
        e['sources'].sort(key=lambda s: (s['levelMin'] is None, s['levelMin'] or 0, s['dungeon'], s['boss']))
    return {
        'schemaVersion': 1,
        'source': {
            'addon': 'CMaNGOS classic-db + cliente WoW Forever',
            'coverage': ('Nombres de ítems del cliente WoW Forever 1.60.1.70888; botín de jefes de dungeons '
                         'y raids de WoW 1.12 (CMaNGOS), aproximado para Forever. Sin los dungeons nuevos de '
                         'Forever. No prueba ligadura, venta ni viabilidad en solitario.'),
            'files': [{'path': 'data/' + n, 'sha256': sha256(n)} for n in ('dungeons.json', 'items.json')],
        },
        'items': dict(sorted(salida.items(), key=lambda kv: int(kv[0]))),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default=OUT)
    args = ap.parse_args()
    cat = construir()
    cuerpo = json.dumps(cat, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    texto = ('/* GENERATED by tools/build-catalogo-mercado.py from data/ (CMaNGOS classic-db GPL-3.0 +\n'
             ' * WoW Forever client tables, (c) Blizzard Entertainment). See LICENSE-DATA.md.\n'
             ' * Exposes window.HunterMarketCatalog. */\n'
             '(function(){\'use strict\';var DATA=' + cuerpo + ';\n'
             'if(typeof module!==\'undefined\'&&module.exports)module.exports=DATA;\n'
             'else if(typeof window!==\'undefined\')window.HunterMarketCatalog=DATA;})();\n')
    with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(texto)
    con = sum(1 for e in cat['items'].values() if e['sources'])
    print(json.dumps({'out': os.path.relpath(args.out, ROOT), 'items': len(cat['items']), 'conFuente': con,
                      'bytes': len(texto.encode('utf-8'))}))


if __name__ == '__main__':
    main()
